#!/usr/bin/env node
// Builds the one SQL script that initialises a NEW, EMPTY Preview Supabase project (R-3):
//   001 → supabase/preview/001a (tables production made in the dashboard, inferred from code) → 002…NNN → synthetic seed.
//   node scripts/release/build-preview-sql.mjs > preview-init.sql      (then paste into the Preview project's SQL Editor)
// The script refuses to run on a database that already has MarkLens tables, so it cannot be applied to production.
import { readFileSync, readdirSync } from "node:fs"

const MIG = "supabase/migrations/", PRE = "supabase/preview/"
export function previewInitFiles() {
  const migrations = readdirSync(MIG).filter(f => /^\d{3}_.+\.sql$/.test(f)).sort().map(f => MIG + f)
  const preview = readdirSync(PRE).filter(f => f.endsWith(".sql")).sort()
  const before002 = preview.filter(f => f < "002").map(f => PRE + f), after = preview.filter(f => f >= "900").map(f => PRE + f)
  return [migrations[0], ...before002, ...migrations.slice(1), ...after]
}

export function previewInitSql() {
  const guard = `-- MarkLens PREVIEW initialisation — generated by scripts/release/build-preview-sql.mjs. NEVER run on production.
DO $$ BEGIN
  IF to_regclass('public.articles') IS NOT NULL OR to_regclass('public.cardnews') IS NOT NULL THEN
    RAISE EXCEPTION 'MarkLens tables already exist — this script only initialises a new, empty Preview project.';
  END IF;
END $$;
`
  return guard + previewInitFiles().map(f => `\n-- ===== ${f} =====\n${readFileSync(f, "utf8")}`).join("\n")
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/release/build-preview-sql.mjs")) process.stdout.write(previewInitSql())
