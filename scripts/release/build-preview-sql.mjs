#!/usr/bin/env node
// Builds the one SQL script that initialises a NEW, EMPTY Preview Supabase project (R-3):
//   001 → supabase/preview/001a (tables production made in the dashboard, as production defines them) → 002…NNN →
//   synthetic seed → production parity → the read-only migration check (the SQL Editor shows that last result: all true).
//   node scripts/release/build-preview-sql.mjs > preview-init.sql      (then paste into the Preview project's SQL Editor)
// It refuses any database whose public schema already has a table — production has dozens — so pasted into the wrong
// project it stops at its first statement and changes nothing. The seed marks the database (app_config
// marklens_environment = preview) so verify-preview-db.mjs can confirm the target from its keys alone.
import { readFileSync, readdirSync } from "node:fs"

const MIG = "supabase/migrations/", PRE = "supabase/preview/"
export function previewInitFiles() {
  const migrations = readdirSync(MIG).filter(f => /^\d{3}_.+\.sql$/.test(f)).sort().map(f => MIG + f)
  const preview = readdirSync(PRE).filter(f => f.endsWith(".sql")).sort()
  const before002 = preview.filter(f => f < "002").map(f => PRE + f), after = preview.filter(f => f >= "900").map(f => PRE + f)
  return [migrations[0], ...before002, ...migrations.slice(1), ...after]
}

export function previewInitSql() {
  const guard = `-- MarkLens PREVIEW initialisation — generated by scripts/release/build-preview-sql.mjs. NEVER run on production.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public') THEN
    RAISE EXCEPTION 'Tables already exist in schema public — this script only initialises a new, empty Preview project. Nothing was changed.';
  END IF;
END $$;
`
  const check = `\n-- ===== result: scripts/release/check-production-schema.sql (read-only) — every row must be true =====\n${readFileSync("scripts/release/check-production-schema.sql", "utf8")}`
  return guard + previewInitFiles().map(f => `\n-- ===== ${f} =====\n${readFileSync(f, "utf8")}`).join("\n") + check
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/release/build-preview-sql.mjs")) process.stdout.write(previewInitSql())
